#!/usr/bin/env python3
"""Packs tests/fixtures/* into app/modules/selftest-data.js (one zip, as base64) so the self-check page works from a flash drive (file://).
   Run this after adding or changing a fixture."""
import base64, io, os, zipfile
here = os.path.dirname(os.path.abspath(__file__))
fx = os.path.join(here, 'fixtures')
buf = io.BytesIO()
with zipfile.ZipFile(buf, 'w', zipfile.ZIP_DEFLATED, compresslevel=9) as z:
    for name in sorted(os.listdir(fx)):
        z.write(os.path.join(fx, name), name)
out = os.path.join(here, '..', 'app', 'modules', 'selftest-data.js')
open(out, 'w').write("/* Generated by tests/build-selftest-data.py — small sample files for the self-check page. Do not edit. */\nconst SELFTEST_ZIP = '" + base64.b64encode(buf.getvalue()).decode() + "';\n")
print(len(buf.getvalue()) // 1024, 'KB zip,', os.path.getsize(out) // 1024, 'KB js')
